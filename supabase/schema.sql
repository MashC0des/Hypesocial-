-- PROFILES POLICIES
DROP POLICY IF EXISTS "Users can view own profile or admin all" ON public.profiles;
CREATE POLICY "Users can view own profile or admin all"
  ON public.profiles FOR SELECT
  USING (auth.uid() = id OR public.is_admin());

DROP POLICY IF EXISTS "Users can update own profile name/company" ON public.profiles;
CREATE POLICY "Users can update own profile name/company"
  ON public.profiles FOR UPDATE
  USING (auth.uid() = id)
  WITH CHECK (
    auth.uid() = id
    AND role = (SELECT role FROM public.profiles WHERE id = auth.uid())
  );

-- SERVICES POLICIES
DROP POLICY IF EXISTS "Anyone can view services" ON public.services;
