-- 1. PROFILES TABLE (Linked 1:1 with Supabase Auth users)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  company TEXT DEFAULT '',
  business_description TEXT DEFAULT '',
  email TEXT UNIQUE NOT NULL,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS business_description TEXT DEFAULT '';

-- 2. SERVICES TABLE (Publicly readable, Admin manageable)
CREATE TABLE IF NOT EXISTS public.services (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  price_inr TEXT NOT NULL,
  price_usd TEXT NOT NULL,
  duration TEXT NOT NULL,
  description TEXT NOT NULL,
  features JSONB NOT NULL DEFAULT '[]'::jsonb,
  is_featured BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. WORKS / CASE STUDIES TABLE (Publicly readable, Admin manageable)
CREATE TABLE IF NOT EXISTS public.works (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  client TEXT NOT NULL,
  region TEXT NOT NULL,
  category TEXT NOT NULL,
  year TEXT NOT NULL,
  description TEXT NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. CLIENT PROJECT BRIEFS TABLE (Authenticated Client CRUD + Admin Review)
CREATE TABLE IF NOT EXISTS public.briefs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  user_name TEXT NOT NULL,
  user_email TEXT NOT NULL,
  company TEXT NOT NULL,
  title TEXT NOT NULL,
  service TEXT NOT NULL,
  budget TEXT NOT NULL,
  deliverables TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Submitted' CHECK (status IN ('Submitted', 'In Progress', 'Approved', 'Rejected')),
  admin_note TEXT NOT NULL DEFAULT 'Brief received. Under review by The Hype Social team.',
  date_formatted TEXT NOT NULL DEFAULT TO_CHAR(NOW(), 'DD Mon YYYY'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. CONTACT MESSAGES / INQUIRIES TABLE (Public insert, Admin read/manage)
CREATE TABLE IF NOT EXISTS public.contact_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT DEFAULT '',
  service_interest TEXT DEFAULT 'General Inquiry',
  subject TEXT DEFAULT 'Project Inquiry',
  message TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'New' CHECK (status IN ('New', 'Reviewed', 'Replied')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ==============================================================================
-- HELPER FUNCTIONS & TRIGGERS
-- ==============================================================================

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE SQL
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin'
  );
$$;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, name, company, business_description, email, role)
  VALUES (
    NEW.id,
    COALESCE(NULLIF(TRIM(NEW.raw_user_meta_data ->> 'name'), ''), SPLIT_PART(NEW.email, '@', 1)),
    COALESCE(TRIM(NEW.raw_user_meta_data ->> 'company'), ''),
    COALESCE(TRIM(NEW.raw_user_meta_data ->> 'business_description'), ''),
    LOWER(NEW.email),
    'user'
  )
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    name = COALESCE(NULLIF(EXCLUDED.name, ''), public.profiles.name),
    company = COALESCE(NULLIF(EXCLUDED.company, ''), public.profiles.company),
    business_description = COALESCE(NULLIF(EXCLUDED.business_description, ''), public.profiles.business_description);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Prevent non-admin users from forging status/admin_note/ownership on briefs
CREATE OR REPLACE FUNCTION public.guard_brief_write()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    IF TG_OP = 'INSERT' THEN
      NEW.user_id := auth.uid();
      NEW.status := 'Submitted';
      NEW.admin_note := 'Brief received. Under review by The Hype Social team.';
    ELSE
      NEW.status := OLD.status;
      NEW.admin_note := OLD.admin_note;
      NEW.user_id := OLD.user_id;
      NEW.user_email := OLD.user_email;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS before_brief_update_guard ON public.briefs;
DROP TRIGGER IF EXISTS before_brief_write_guard ON public.briefs;
CREATE TRIGGER before_brief_write_guard
  BEFORE INSERT OR UPDATE ON public.briefs
  FOR EACH ROW EXECUTE FUNCTION public.guard_brief_write();

-- Prevent non-admin users from altering role, id, or email on profiles
CREATE OR REPLACE FUNCTION public.guard_profile_update()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    NEW.id := OLD.id;
    NEW.email := OLD.email;
    NEW.role := OLD.role;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS before_profile_update_guard ON public.profiles;
CREATE TRIGGER before_profile_update_guard
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.guard_profile_update();

-- Force safe initial status on public contact form submissions
CREATE OR REPLACE FUNCTION public.guard_contact_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    NEW.status := 'New';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS before_contact_insert_guard ON public.contact_messages;
CREATE TRIGGER before_contact_insert_guard
  BEFORE INSERT ON public.contact_messages
  FOR EACH ROW EXECUTE FUNCTION public.guard_contact_insert();

-- Database-level length & format guards (idempotent)
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'contact_messages_len_check') THEN
    ALTER TABLE public.contact_messages
      ADD CONSTRAINT contact_messages_len_check
      CHECK (
        char_length(trim(name)) BETWEEN 1 AND 150
        AND char_length(trim(email)) BETWEEN 3 AND 160
        AND email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'
        AND char_length(trim(message)) BETWEEN 1 AND 4000
      );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'briefs_len_check') THEN
    ALTER TABLE public.briefs
      ADD CONSTRAINT briefs_len_check
      CHECK (
        char_length(trim(title)) BETWEEN 1 AND 250
        AND char_length(trim(deliverables)) BETWEEN 1 AND 4000
      );
  END IF;
END $$;

